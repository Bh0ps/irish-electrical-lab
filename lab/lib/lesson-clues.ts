export function lessonClue(id:number,kind:'predict'|'explain',doc:CircuitDocument) {
  if (kind === 'explain' && id === 72) {
    const mark = (terminal:string) => describeEndpoint(doc,{component:'chime',terminal})?.pointLabel;
    const front = mark('FRONT'), back = mark('REAR');
    if (front && back) return `Trace the wires from ${front} and ${back} on the chime. Which button does each wire go to?`;
  }
  return (kind === 'explain' && explanationClues[id]) || clues[id];
}
